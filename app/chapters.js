const CODE_RE = /(必修|選\s*(?:III|II|IV|V|I|Ⅲ|Ⅱ|Ⅳ|Ⅴ|Ⅰ))\s*([1-4]-[1-5])/g;
const ROMAN = { 'Ⅰ': 'I', 'Ⅱ': 'II', 'Ⅲ': 'III', 'Ⅳ': 'IV', 'Ⅴ': 'V' };

// 從字串找出所有章節代碼，回傳 ['選III 1-3', ...]（去重、只保留對照表內的）
function chapterCodes(s) {
  const out = [];
  if (!s) return out;
  for (const m of String(s).matchAll(CODE_RE)) {
    let b = m[1].replace(/\s/g, '');
    for (const k in ROMAN) b = b.replace(k, ROMAN[k]);
    if (SEC[b] && SEC[b][m[2]]) {
      const code = b + ' ' + m[2];
      if (!out.includes(code)) out.push(code);
    }
  }
  return out;
}
function chapterName(code) {       // '選III 1-3' -> '選III 1-3 勒沙特列原理'
  const [b, s] = code.split(' ');
  return SEC[b] && SEC[b][s] ? `${code} ${SEC[b][s]}` : code;
}
function chapterOrder(code) {      // 排序用數值
  const [b, s] = code.split(' ');
  const bi = BOOKS.indexOf(b);
  return (bi < 0 ? 9 : bi) * 100 + Number(s[0]) * 10 + Number(s[2]);
}
